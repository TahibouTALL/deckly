// Packs the open-licensed elements downloaded by npm into app/assets/ so the editor works offline.
// Run: node tools/build-assets.mjs   (after `npm install` inside tools/)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const nm = path.join(here, 'node_modules');
const app = path.join(here, '..', 'app');
const out = path.join(app, 'assets');
const mk = (p) => fs.mkdirSync(p, { recursive: true });
mk(path.join(out, 'icons')); mk(path.join(out, 'fonts')); mk(path.join(app, 'vendor'));
const credits = [];

// 1. Lucide line icons (ISC)
{
  const dir = path.join(nm, 'lucide-static', 'icons');
  const tags = JSON.parse(fs.readFileSync(path.join(nm, 'lucide-static', 'tags.json'), 'utf8'));
  const icons = {};
  for (const f of fs.readdirSync(dir)) {
    if (!f.endsWith('.svg')) continue;
    const name = f.slice(0, -4);
    const svg = fs.readFileSync(path.join(dir, f), 'utf8');
    const inner = svg.replace(/<!--.*?-->/s, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
    icons[name] = { b: inner, t: (tags[name] || []).slice(0, 8).join(' ') };
  }
  fs.writeFileSync(path.join(out, 'icons', 'lucide.json'), JSON.stringify(icons));
  credits.push(['Lucide icons', 'ISC', 'https://lucide.dev', Object.keys(icons).length]);
}

// 2. Fluent Emoji Flat stickers (MIT) — skin-tone variants skipped
{
  const pkg = path.join(nm, '@iconify-json', 'fluent-emoji-flat');
  const data = JSON.parse(fs.readFileSync(path.join(pkg, 'icons.json'), 'utf8'));
  const cats = JSON.parse(fs.readFileSync(path.join(pkg, 'metadata.json'), 'utf8')).categories || {};
  const catOf = {};
  for (const [c, list] of Object.entries(cats)) for (const n of list) catOf[n] = c;
  const tone = /-(light|medium-light|medium|medium-dark|dark)$/;
  const icons = {};
  for (const [name, v] of Object.entries(data.icons)) {
    if (tone.test(name)) continue;
    icons[name] = { b: v.body, c: catOf[name] || 'Other', w: v.width || data.width || 32, h: v.height || data.height || 32 };
  }
  fs.writeFileSync(path.join(out, 'icons', 'stickers.json'), JSON.stringify(icons));
  credits.push(['Fluent Emoji (Microsoft)', 'MIT', 'https://github.com/microsoft/fluentui-emoji', Object.keys(icons).length]);
}

// 3. Brand logos (CC0)
{
  const data = JSON.parse(fs.readFileSync(path.join(nm, '@iconify-json', 'logos', 'icons.json'), 'utf8'));
  const icons = {};
  for (const [name, v] of Object.entries(data.icons)) icons[name] = { b: v.body, w: v.width || data.width || 256, h: v.height || data.height || 256 };
  fs.writeFileSync(path.join(out, 'icons', 'logos.json'), JSON.stringify(icons));
  credits.push(['SVG Logos (gilbarbara)', 'CC0', 'https://github.com/gilbarbara/logos', Object.keys(icons).length]);
}

// 4. Fonts (SIL Open Font License) — latin 400 + 700
{
  const fonts = [
    ['inter', 'Inter'], ['poppins', 'Poppins'], ['montserrat', 'Montserrat'], ['playfair-display', 'Playfair Display'],
    ['lora', 'Lora'], ['bebas-neue', 'Bebas Neue'], ['dm-serif-display', 'DM Serif Display'], ['space-grotesk', 'Space Grotesk'],
    ['caveat', 'Caveat'], ['pacifico', 'Pacifico'], ['oswald', 'Oswald'], ['nunito', 'Nunito'], ['raleway', 'Raleway'],
    ['roboto-slab', 'Roboto Slab'], ['archivo-black', 'Archivo Black'], ['fira-code', 'Fira Code'],
  ];
  let css = '/* Generated by tools/build-assets.mjs — all fonts SIL Open Font License */\n';
  const list = [];
  for (const [id, family] of fonts) {
    const dir = path.join(nm, '@fontsource', id, 'files');
    let any = false;
    for (const w of [400, 700]) {
      const f = `${id}-latin-${w}-normal.woff2`;
      if (!fs.existsSync(path.join(dir, f))) continue;
      fs.copyFileSync(path.join(dir, f), path.join(out, 'fonts', f));
      css += `@font-face{font-family:'${family}';font-weight:${w};font-style:normal;font-display:swap;src:url('${f}') format('woff2');}\n`;
      any = true;
    }
    if (any) list.push(family);
  }
  fs.writeFileSync(path.join(out, 'fonts', 'fonts.css'), css);
  fs.writeFileSync(path.join(out, 'fonts', 'fonts.json'), JSON.stringify(list));
  credits.push(['Fonts via Fontsource', 'SIL OFL 1.1', 'https://fontsource.org', list.length]);
}

// 5. Vendor libraries (MIT)
fs.copyFileSync(path.join(nm, 'pptxgenjs', 'dist', 'pptxgen.bundle.js'), path.join(app, 'vendor', 'pptxgen.bundle.js'));
fs.copyFileSync(path.join(nm, 'html-to-image', 'dist', 'html-to-image.js'), path.join(app, 'vendor', 'html-to-image.js'));
fs.copyFileSync(path.join(nm, 'jspdf', 'dist', 'jspdf.umd.min.js'), path.join(app, 'vendor', 'jspdf.umd.min.js'));

fs.writeFileSync(path.join(out, 'credits-packs.json'), JSON.stringify(credits, null, 1));
console.log(credits.map((c) => `${c[0]}: ${c[3]} (${c[1]})`).join('\n'));
